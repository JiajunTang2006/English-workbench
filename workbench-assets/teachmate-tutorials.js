  // 示例随当前学科生成，避免数学、地理等工作区显示语法和完形的英语问法。
  window.tmPluginGuideForSubject = function (pluginId, subject) {
    var guide = window.TM_PLUGIN_GUIDES[pluginId];
    if (!guide || !subject || subject.key === 'english') return guide;
    var label = subject.label || '本学科';
    var dimensions = Array.isArray(subject.analysis_dimensions) ? subject.analysis_dimensions : [];
    var focus = dimensions.slice(0, 2).join('和') || '当前学科的薄弱点';
    var examples = {
      exam_analysis: [
        '分析这次' + label + '考试的均分、得分率和分层，并列出有证据的薄弱知识点',
        '比较本学期同类' + label + '考试的得分率变化；满分不同的考试请不要直接比较原始分数',
        '找出这次' + label + '考试中需要优先讲评的题目，并说明数据依据',
      ],
      student_diagnosis: [
        '根据这次' + label + '考试，为当前班级生成有证据支持的学生画像',
        '重点分析在' + focus + '方面有明确题目证据的学生',
        '分析指定学生这次' + label + '考试的表现，更新画像并注明数据不足的地方',
      ],
      review_plan: [
        '根据这次' + label + '考试，生成讲评流程、学生练习单、教师答案和课后复测草稿',
        '下周有四课时，请围绕' + focus + '安排分层复习；仅使用已核验的考试证据',
        '按本次考试中证据明确的薄弱知识点安排复习，分别给基础层和提高层设计练习',
      ],
    };
    return Object.assign({}, guide, { prompts: examples[pluginId] || guide.prompts });
  };
